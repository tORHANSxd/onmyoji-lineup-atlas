"""Validate and export the original Hunling solo routes from the packed client tables."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

from hunling_stage import CAPTURE_ITEMS, HUNLING_BOSS, HUNLING_NORMAL, challenge_stages, exploration_stages


def extract(root):
    index = json.loads((root / "index.json").read_bytes())
    if index["resourceVersion"] != "0.0.816":
        raise ValueError("Hunling routes require the matching client tables")
    by_name = {row["name"]: row for row in index["tables"]}
    table_hashes = {}

    def table(name):
        record = by_name[name]
        payload = (root / (name + ".json.gz")).read_bytes()
        if hashlib.sha256(payload).hexdigest() != record["sha256"]:
            raise ValueError(f"Client table checksum mismatch: {name}")
        table_hashes[name] = record["source"]["marshalSHA256"]
        return dict(json.loads(gzip.decompress(payload)))

    pve, groups = table("pve_stage_data"), table("BattleMonstersInfo")
    regions, spirits, levels = table("hunling_tansuo"), table("hunling_base"), table("hunling_tansuo_lv")
    codes = {row["search_id"]: key for key, row in table("team_assist_stage").items()
             if row["yys_num"] == 1 and row["ss_num"] == 5 and row["name"].startswith("契灵")}
    props = table("hunling_prop")
    items = {item: props[item]["name"] for item in CAPTURE_ITEMS}
    routes = {}
    for stage_id, (region, level, spirit, scene) in (*exploration_stages(), *challenge_stages()):
        stage = pve[str(stage_id)]
        group_id = stage["groupid"]
        group = groups[group_id]
        if group_id != stage_id or group["resindex"] != scene or len(group["MonstersInfos"]) != 1 or stage["shishentotal"] != 5:
            raise ValueError(f"Unexpected client route for {stage_id}")
        title = f"{regions[region]['name']} · 探查 {level} 级"
        targets = []
        if spirit is not None:
            if (spirit not in regions[region]["hunling_ids"]
                    or group["MonstersInfos"][0][0][1] != spirits[spirit]["boss_skills"][level - 1]):
                raise ValueError(f"Unexpected Hunling species for {stage_id}")
            title += f" · {spirits[spirit]['name']}"
            stars = sorted({levels[level][key][0] for key in ("hunling_begin_star", "hunling_end_star")})
            targets = [codes[30000 + (spirit - 100) * 10 + star] for star in stars]
        routes[stage_id] = {"battleMode": HUNLING_NORMAL if spirit is None else HUNLING_BOSS, "groupId": group_id,
                            "sceneId": scene, "regionId": region, "exploreLevel": level, "spiritId": spirit,
                            "label": title, "codeStageIds": targets, "units": [unit[:3] for unit in group["MonstersInfos"][0] if unit[1]]}
    return {"resourceVersion": index["resourceVersion"], "routes": routes, "items": items, "tableSHA256": table_hashes}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    data = extract(args.catalog)
    header = "// Generated by tools/verify-hunling-openings.py from the verified client tables.\n"
    header += "(function(root){\n'use strict';\nconst routes={\n"
    rows = "\n".join(f" {key}:{json.dumps(row, ensure_ascii=False, separators=(',', ':'))}," for key, row in data["routes"].items())
    footer = "\n};\nconst items=" + json.dumps(data["items"], ensure_ascii=False) + ";\n"
    footer += "const tableSHA256=" + json.dumps(data["tableSHA256"]) + ";\n"
    footer += f"const value={{resourceVersion:'{data['resourceVersion']}',routes,items,tableSHA256,battleModes:[{HUNLING_NORMAL},{HUNLING_BOSS}]}};\n"
    footer += "if(typeof module==='object'&&module.exports)module.exports=value;else root.AtlasHunlingEncounters=value;\n})(globalThis);\n"
    args.output.write_text(header + rows + footer, encoding="utf-8")
