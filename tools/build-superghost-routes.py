"""Read pinned Super Ghost formations and date-specific bonuses from the catalog."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

from superghost_stage import SUPERGHOST_MODE, SUPERGHOST_STAGES, ghost_route, ghost_special_attack


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("script_index", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    index = json.loads((args.catalog / "index.json").read_bytes())
    scripts = json.loads(args.script_index.read_bytes())
    if any(scripts.get(key, index[key]) != index[key] for key in ("nativeSHA256", "resourceVersion")):
        raise ValueError("Super Ghost sources are from different client versions")
    script_modules = {item["module"].replace("\\", "/").removeprefix("lib3/"): item["marshalSHA256"]
                      for item in scripts["modules"]}
    tables = {row["name"]: row for row in index["tables"]}
    hashes = {}

    def load(name):
        table = tables[name]
        data = (args.catalog / (name + ".json.gz")).read_bytes()
        source = table["source"]
        hashes[name] = source["marshalSHA256"]
        if hashlib.sha256(data).hexdigest() != table["sha256"] or script_modules.get(source["module"]) != hashes[name]:
            raise ValueError(f"Invalid original table {name}")
        return dict(json.loads(gzip.decompress(data)))

    missions = load("SuperGhost_mission")
    monsters = load("monster")
    schedule = load("super_ghost_hjs_special_attack")
    groups = load("super_ghost_hjs_special_attack_group")
    constants = load("Constant")
    codes = load("team_assist_stage")
    if missions.keys() != SUPERGHOST_STAGES:
        raise ValueError("The original mission range changed")
    stages = {}
    for stage_id in sorted(missions):
        row = missions[stage_id]
        stages[stage_id] = ghost_route(stage_id, row, monsters)
    days = {day: {"date": schedule[day]["begin_time"][:3], "groups": ghost_special_attack(day, schedule, groups)}
            for day in sorted(schedule)}
    code_ids = {}
    for star in (5, 6):
        (code_id,) = [key for key, item in codes.items() if item["name"] == f"{star}星超鬼王"
                      and (item["ss_num"], item["yys_num"]) == (5, 1)]
        code_ids[star] = code_id
    meta = {"resourceVersion": index["resourceVersion"], "tableSHA256": hashes, "battleMode": SUPERGHOST_MODE,
            "engineSHA256": script_modules["battleengine/engine/SuperGhostEngine.py"], "days": days,
            "codeStageIds": code_ids, "attackReductions": [-constants[key]["value"][0] for key in (7096, 7097)]}
    metadata = json.dumps(meta, ensure_ascii=False, indent=2).removesuffix("\n}")
    rows = ",\n".join(f"  {key}:{json.dumps(row, ensure_ascii=False, separators=(',', ':'))}" for key, row in stages.items())
    source = ("// Generated by tools/build-superghost-routes.py.\n(function(root){\n 'use strict';\n const data=" + metadata
              + ',\n "routes":{\n' + rows + "\n }\n };\n"
              + " if(typeof module==='object'&&module.exports)module.exports=data;else root.AtlasSuperGhost=data;\n})(globalThis);\n")
    args.output.write_text(source, encoding="utf-8", newline="\n")
    print(f"{len(stages)} missions, {len(days)} daily special attack settings")


if __name__ == "__main__":
    main()
