"""Generate the pinned Guild Crevice stage map from the local client catalog."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

from guild_crevice_stage import CREVICE_MODE, CREVICE_SCENE, CREVICE_STAGES, CREVICE_TIME, crevice_route


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("script_index", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    index = json.loads((args.catalog / "index.json").read_bytes())
    scripts = json.loads(args.script_index.read_bytes())
    if any(scripts.get(key, index[key]) != index[key] for key in ("nativeSHA256", "resourceVersion")):
        raise ValueError("The Guild Crevice sources are from different client versions")
    tables = {table["name"]: table for table in index["tables"]}
    script_modules = {item["module"].replace("\\", "/").removeprefix("lib3/"): item["marshalSHA256"]
                      for item in scripts["modules"]}
    hashes = {}

    def load(name):
        table = tables[name]
        data = (args.catalog / (name + ".json.gz")).read_bytes()
        if hashlib.sha256(data).hexdigest() != table["sha256"]:
            raise ValueError(f"Invalid original table {name}")
        hashes[name] = table["source"]["marshalSHA256"]
        if script_modules.get(table["source"]["module"]) != hashes[name]:
            raise ValueError(f"The original table {name} differs from the script index")
        return dict(json.loads(gzip.decompress(data)))

    stages = load("pve_stage_data")
    monsters = load("BattleMonstersInfo")
    targets = load("guild_crevice_battle")
    areas = load("guild_crevice_area")
    codes = load("team_assist_stage")
    modes = load("normal_battle_config")
    if modes[CREVICE_MODE]["halt_time"] != CREVICE_TIME:
        raise ValueError("The original Guild Crevice battle clock changed")
    code_by_area = {}
    for area, row in areas.items():
        (code_id,) = [id_ for id_, code in codes.items() if (code["yys_num"], code["ss_num"]) == (1, 5)
                      and code["name"] == "狭间暗域·" + row["name"]]
        code_by_area[area] = code_id
    routes = {}
    for stage_id in sorted(CREVICE_STAGES):
        row = stages[str(stage_id)]
        route = crevice_route(stage_id, row, monsters[row["groupid"]], targets)
        route["label"] = row["name"].removeprefix("阴界裂缝")
        route["codeStageIds"] = [code_by_area[route["area"]]] if route["area"] else sorted(code_by_area.values())
        routes[stage_id] = route
    (engine,) = [record for record in scripts["modules"] if record["module"].replace("\\", "/")
                 .endswith("battleengine/engine/GuildLiefeng2022Engine.py")]
    metadata = {"resourceVersion": index["resourceVersion"], "engineSHA256": engine["marshalSHA256"],
                "tableSHA256": hashes, "battleMode": CREVICE_MODE, "sceneId": CREVICE_SCENE, "deadlineSeconds": CREVICE_TIME}
    double_indent = json.dumps(metadata, ensure_ascii=False, indent=2).removesuffix("\n}")
    rows = ",\n".join(f"  {key}:{json.dumps(row, ensure_ascii=False, separators=(',', ':'))}" for key, row in routes.items())
    source = ("// Generated by tools/build-crevice-routes.py.\n(function(root){\n 'use strict';\n const data=" + double_indent
              + ',\n "routes":{\n' + rows + "\n }\n };\n"
              + " if(typeof module==='object'&&module.exports)module.exports=data;else root.AtlasGuildCrevice=data;\n})(globalThis);\n")
    args.output.write_text(source, encoding="utf-8", newline="\n")
    print(f"{len(routes)} Guild Crevice stage records, {len({row['groupId'] for row in routes.values()})} formations")


if __name__ == "__main__":
    main()
