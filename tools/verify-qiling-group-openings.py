"""Extract collective Hunling boss life pools using the original battle code."""

import argparse
import json
import os
from pathlib import Path
import sys
from tempfile import TemporaryDirectory

sys.path.insert(0, str(Path(__file__).resolve().parent))
from qiling_group_stage import QILING_GROUP_LIMIT, QILING_GROUP_MODE, group_encounter
from rune_floor_host import prepare_runtime


def extract(runtime, work):
    modules, _, evidence = prepare_runtime(runtime, work)
    from battleengine.engine.QiLingGroupBossBattleEngine import DATA_HUNLING_BOSS
    from com.data.cdata import team_assist_stage
    from DynamicConfigData import DATA_HUNLING_BASE

    codes = {row["search_id"]: id_ for id_, row in team_assist_stage.data.items()
             if row["name"].startswith("契灵首领") and row["yys_num"] == 1 and row["ss_num"] == 5}
    rows, shared_hp = {}, {}
    for config_id in sorted(DATA_HUNLING_BOSS.data):
        engine, config, group, _ = group_encounter(config_id)
        spirit = config["hunling_id"]
        group_id = group["ID"]
        if group_id not in shared_hp:
            shared_hp[group_id] = engine.calcSharedMonMaxHp(str(group_id), True)["1"]
        position, enemy, level, *_ = group["MonstersInfos"][0][0]
        skill, skill_level, scope = config["skills"]
        if position != 1 or skill_level != 1 or scope not in (0, 1):
            raise ValueError("Unexpected collective Hunling skill or formation")
        rows[config_id] = {"name": DATA_HUNLING_BASE.data[spirit]["name"], "spiritId": spirit,
                           "groupId": group_id, "sceneId": group["resindex"], "enemyId": enemy, "enemyLevel": level,
                           "maxHp": shared_hp[group_id], "skillId": skill, "skillTargets": 6 if scope == 0 else 1,
                           "codeStageId": codes[38000 + spirit - 100]}
    tables = ("hunling_boss", "hunling_base", "pve_stage_data", "BattleMonstersInfo", "team_assist_stage", "system_rule_dsc")
    values = {"resourceVersion": evidence["resourceVersion"], "battleMode": QILING_GROUP_MODE,
              "windowLimit": QILING_GROUP_LIMIT, "tableSHA256": {name: modules.rows["com.data.cdata." + name]["marshalSHA256"] for name in tables},
              "engineSHA256": modules.rows["battleengine.engine.QiLingGroupBossBattleEngine"]["marshalSHA256"]}
    return values, rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    runtime = json.loads(args.runtime.read_text(encoding="utf-8-sig"))
    sys.path.insert(1, runtime["gameTools"])
    previous = Path.cwd()
    with TemporaryDirectory(prefix="yuqi-qiling-group-openings-") as work:
        try:
            os.chdir(work)
            data, routes = extract(runtime, Path(work))
        finally:
            os.chdir(previous)
    plain = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    source = "// Generated by tools/verify-qiling-group-openings.py from the matching runtime.\n(function(root){\n'use strict';\n"
    source += "const routes={\n" + "\n".join(f" {key}:{plain(row)}," for key, row in routes.items()) + "\n};\n"
    source += "const data={..." + plain(data) + ",routes};\n"
    source += "if(typeof module==='object'&&module.exports)module.exports=data;else root.AtlasQiLingGroups=data;\n})(globalThis);\n"
    args.output.write_text(source, encoding="utf-8")
